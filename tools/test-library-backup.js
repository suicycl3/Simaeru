const { app } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { buildSync } = require('esbuild');
const root = path.resolve(__dirname, '..');
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'mylibrary-backup-test-'));
app.setPath('userData', path.join(work, 'profile'));
app.whenReady().then(async () => {
  try {
    const out = path.join(root, 'out/test/backup-test.cjs');
    buildSync({ stdin: { contents: "export * from './src/main/db/database'; export * from './src/main/db/backup'; export { Repo } from './src/main/db/repo';", loader: 'ts', resolveDir: root }, outfile: out, bundle: true, platform: 'node', format: 'cjs', external: ['electron', 'better-sqlite3'], alias: { '@shared': path.join(root, 'src/shared') }, logLevel: 'error' });
    const api = require(out);
    const dir = app.getPath('userData');
    let { db } = api.openDatabase(dir);
    const repo = new api.Repo(db);
    assert.equal(repo.getSetting('contract'), null);
    repo.setSetting('contract', 'original');
    assert.throws(() => db.transaction(() => {
      repo.setSetting('contract', 'rolled-back');
      repo.startSyncRun('rollback');
      throw new Error('rollback');
    })());
    assert.equal(repo.getSetting('contract'), 'original');
    assert.deepEqual(repo.syncHistory(), []);
    assert.equal(repo.lastSuccessfulSyncAt(), null);
    const run = repo.startSyncRun('dmm');
    assert.equal(repo.syncHistory()[0].status, 'running');
    repo.finishSyncRun(run, 'done', []);
    const completedAt = repo.lastSuccessfulSyncAt();
    assert.equal(typeof completedAt, 'number');
    const failed = repo.startSyncRun('dmm');
    repo.finishSyncRun(failed, 'error', [{ floorKey: 'dmm:book', error: 'fixture' }]);
    assert.equal(repo.lastSuccessfulSyncAt(), completedAt);
    assert.equal(repo.syncHistory()[0].floors[0].error, 'fixture');
    db.prepare('UPDATE sync_runs SET detail=? WHERE id=?').run('invalid legacy JSON', failed);
    assert.deepEqual(repo.syncHistory()[0].floors, []);
    console.log('PASS repository settings/history: same-connection rollback, status, successful timestamp and legacy JSON');
    db.prepare("INSERT INTO products(site_id,floor_id,product_id,title,first_seen_at,last_synced_at,favorite_at) VALUES('dlsite','doujin','test','saved title',1,1,99)").run();
    db.prepare("INSERT INTO settings(key,value) VALUES('test-setting','saved')").run();
    db.prepare("INSERT INTO credentials(site_id,login_id,secret,updated_at) VALUES('dmm',?,?,1)").run(Buffer.from('private-id'), Buffer.from('private-secret'));
    const file = path.join(work, 'backup.db');
    await api.exportLibrary(file);
    const Database = require('better-sqlite3');
    const snapshot = new Database(file, { readonly: true });
    assert.equal(snapshot.prepare('SELECT count(*) n FROM credentials').get().n, 0);
    assert.equal(snapshot.prepare('SELECT favorite_at n FROM products').get().n, 99);
    snapshot.close();
    assert.equal(fs.readFileSync(file).includes(Buffer.from('private-secret')), false);
    db.prepare("UPDATE products SET title='changed'").run();
    db.prepare("UPDATE credentials SET secret=?").run(Buffer.from('current-secret'));
    await api.stageLibraryRestore(file, dir);
    api.closeDatabase();
    api.applyPendingRestore(dir);
    ({ db } = api.openDatabase(dir));
    assert.equal(db.prepare('SELECT title FROM products').get().title, 'saved title');
    assert.equal(db.prepare('SELECT value FROM settings WHERE key=?').get('test-setting').value, 'saved');
    assert.equal(db.prepare('SELECT secret FROM credentials').get().secret.toString(), 'current-secret');
    assert(fs.readdirSync(dir).some(name => name.startsWith('library.db.before-restore-')));
    const invalid = path.join(work, 'invalid.db'); fs.writeFileSync(invalid, 'not a database');
    await assert.rejects(api.stageLibraryRestore(invalid, dir));
    assert.equal(db.prepare('SELECT title FROM products').get().title, 'saved title');
    api.closeDatabase();
    console.log('PASS backup: consistent snapshot, no credential bytes, restore favorites/settings, retain current credentials and previous database, reject invalid backup');
    app.exit(0);
  } catch (error) { console.error(error); app.exit(1); }
});
